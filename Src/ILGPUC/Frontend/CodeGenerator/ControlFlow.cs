using ILGPUC.IR;
using ILGPUC.IR.MethodValues;
using ILGPUC.IR.ModuleValues;
using ILGPUC.IR.PureValues;
using System;
using System.Collections.Generic;

namespace ILGPUC.Frontend;

partial class CodeGenerator
{
    /// <summary>
    /// Realizes a return instruction.
    /// </summary>
    private void MakeReturn()
    {
        var returnType = MethodBuilder.Method.Type;

        if (returnType is VoidType)
            Builder.CreateReturnTermination();
        else
            Builder.CreateReturnTermination(Block.Pop(returnType, ConvertFlags.None));
    }

    /// <summary>
    /// Realizes an unconditional branch instruction.
    /// </summary>
    private void MakeBranch()
    {
        var successors = Block.GetPendingSuccessors(1);
        Builder.CreateUnconditionalTermination(successors[0]);
    }

    /// <summary>
    /// Realizes a conditional branch instruction.
    /// </summary>
    /// <param name="compareKind">The comparison type of the condition.</param>
    /// <param name="instructionFlags">The instruction flags.</param>
    private void MakeBranch(
        CompareKind compareKind,
        ILInstructionFlags instructionFlags)
    {
        var successors = Block.GetPendingSuccessors(2);

        var condition = CreateCompare(compareKind, instructionFlags);
        CreateConditionalBranch(condition, successors[0], successors[1]);
    }

    /// <summary>
    /// Make an intrinsic branch.
    /// </summary>
    /// <param name="kind">The current compare kind.</param>
    private void MakeIntrinsicBranch(CompareKind kind)
    {
        var comparisonValue = Block.PopCompareValue(Location, ConvertFlags.None);

        var successors = Block.GetPendingSuccessors(2);

        // Delegate caching pattern: the delegate caches generated by the C#
        // compiler are empty in kernel code (see _delegateCacheLoads), and
        // other null constants are null as well: `null != null` is always
        // false. Fold directly to an unconditional branch and clean up the
        // dead target's predecessor edges.
        bool isCacheLoad = _delegateCacheLoads.Contains(comparisonValue);
        if (!isCacheLoad)
            VerifyNoDelegateNullTest(comparisonValue);
        if (isCacheLoad || comparisonValue is NullValue)
        {
            // brtrue (NotEqual): null != 0 -> false -> take false branch
            // brfalse (Equal): null == 0 -> true -> take true branch
            bool isTrue = kind != CompareKind.NotEqual;
            var liveTarget = isTrue ? successors[0] : successors[1];
            var deadTarget = isTrue ? successors[1] : successors[0];

            // The CFGBuilder's SetupPredecessors wired edges based on the
            // pending termination which included both targets. Now that the
            // branch is folded, remove the dead edge and every block that
            // becomes unreachable.
            if (!TryFoldBranch(liveTarget, deadTarget))
            {
                Builder.CreateUnfoldedConditionalTermination(
                    Builder.CreatePrimitiveValue(Location, isTrue),
                    successors[0],
                    successors[1]);
            }
            return;
        }

        // For pointer types, compare against a null of the same pointer type
        // instead of a primitive zero to avoid Int64 → ptr conversion failures.
        var rightValue = comparisonValue.Type is AddressSpaceType
            ? Builder.CreateNull(Location, comparisonValue.Type)
            : Builder.CreatePrimitiveValue(
                Location,
                comparisonValue.BasicValueType,
                0);

        var condition = CreateCompare(
            comparisonValue,
            rightValue,
            kind,
            CompareFlags.None);
        CreateConditionalBranch(condition, successors[0], successors[1]);
    }

    /// <summary>
    /// Creates a conditional branch. A constant condition (e.g. the
    /// <c>ldc.i4.1; brtrue</c> sequences that debug builds emit around switch
    /// expressions) is folded to an unconditional branch, and the dead edge is
    /// removed so that the dead target no longer counts as a predecessor.
    /// Otherwise SSA construction would still feed phis from the unreachable
    /// block, which is never sealed.
    /// </summary>
    /// <param name="condition">The branch condition.</param>
    /// <param name="trueTarget">The target if the condition holds.</param>
    /// <param name="falseTarget">The target otherwise.</param>
    private void CreateConditionalBranch(
        Value condition,
        BasicBlock trueTarget,
        BasicBlock falseTarget)
    {
        if (condition is PrimitiveValue primitive && trueTarget != falseTarget)
        {
            bool isTrue = primitive.Int1Value;
            var liveTarget = isTrue ? trueTarget : falseTarget;
            var deadTarget = isTrue ? falseTarget : trueTarget;
            if (TryFoldBranch(liveTarget, deadTarget))
                return;
            Builder.CreateUnfoldedConditionalTermination(
                condition,
                trueTarget,
                falseTarget);
            return;
        }

        Builder.CreateConditionalTermination(condition, trueTarget, falseTarget);
    }

    /// <summary>
    /// Replaces the pending branch of the current block by an unconditional
    /// branch to <paramref name="liveTarget"/>, removes the edge to
    /// <paramref name="deadTarget"/> and prunes every block that becomes
    /// unreachable.
    /// </summary>
    /// <param name="liveTarget">The target that is still branched to.</param>
    /// <param name="deadTarget">The target that is no longer branched to.</param>
    /// <returns>
    /// False if the branch was not folded because the method has irreducible
    /// control flow (C# <c>goto</c> into a loop). There, reverse post order does
    /// not process all predecessors of a block first, so a fold could leave a
    /// reachable block whose only remaining predecessor has not been processed,
    /// or make an already processed block unreachable. The caller then emits the
    /// conditional branch, which later passes fold.
    /// </returns>
    private bool TryFoldBranch(BasicBlock liveTarget, BasicBlock deadTarget)
    {
        if (IsIrreducible)
            return false;
        Builder.CreateUnconditionalTermination(liveTarget);
        deadTarget.RemovePredecessor(Block.BasicBlock);
        PruneUnreachableBlocks();
        return true;
    }

    /// <summary>
    /// Returns true if the method has irreducible control flow: a retreating
    /// edge (to a block earlier in reverse post order) whose target does not
    /// dominate its source. Computed once, on the control flow of the IL.
    /// </summary>
    private bool IsIrreducible => _isIrreducible ??= ComputeIsIrreducible();

    /// <summary>
    /// Computes <see cref="IsIrreducible"/> with the iterative dominator algorithm
    /// of Cooper, Harvey and Kennedy over the blocks in reverse post order.
    /// </summary>
    private bool ComputeIsIrreducible()
    {
        var order = new Dictionary<BasicBlock, int>(ReferenceEqualityComparer.Instance);
        var blocks = new List<BasicBlock>();
        foreach (BasicBlock block in _cfgBuilder.Blocks)
        {
            order[block] = blocks.Count;
            blocks.Add(block);
        }

        var idom = new int[blocks.Count];
        Array.Fill(idom, -1);
        idom[0] = 0;
        int Intersect(int a, int b)
        {
            while (a != b)
            {
                while (a > b)
                    a = idom[a];
                while (b > a)
                    b = idom[b];
            }
            return a;
        }

        bool changed = true;
        while (changed)
        {
            changed = false;
            for (int i = 1; i < blocks.Count; ++i)
            {
                int newIdom = -1;
                foreach (var predecessor in blocks[i].Predecessors)
                {
                    if (!order.TryGetValue(predecessor, out int p) || idom[p] < 0)
                        continue;
                    newIdom = newIdom < 0 ? p : Intersect(p, newIdom);
                }
                if (newIdom >= 0 && idom[i] != newIdom)
                {
                    idom[i] = newIdom;
                    changed = true;
                }
            }
        }

        bool Dominates(int dominator, int block)
        {
            while (block != dominator && idom[block] >= 0 && idom[block] != block)
                block = idom[block];
            return block == dominator;
        }

        for (int i = 0; i < blocks.Count; ++i)
        {
            foreach (var successor in blocks[i].Successors)
            {
                if (order.TryGetValue(successor, out int target) &&
                    target <= i &&
                    !Dominates(target, i))
                {
                    return true;
                }
            }
        }
        return false;
    }

    /// <summary>
    /// Finds the blocks that can no longer be reached from the entry block and
    /// removes them as predecessors of their successors, so that SSA
    /// construction neither waits for them nor feeds phis from them, and code
    /// generation skips them before anything they contain is rejected.
    /// </summary>
    /// <remarks>
    /// Reachability is computed by a forward walk from the entry block, because
    /// counting predecessors misses dead cycles: the latch of an unreachable loop
    /// keeps its header alive. Processed blocks contribute the successors of
    /// their emitted terminator, the others those of their pending terminator.
    /// Blocks that were already processed are always reachable, since the
    /// blocks are processed in reverse post order.
    /// </remarks>
    private void PruneUnreachableBlocks()
    {
        var reachable = new HashSet<BasicBlock>(ReferenceEqualityComparer.Instance);
        var workList = new Stack<BasicBlock>();
        reachable.Add(EntryBlock.BasicBlock);
        workList.Push(EntryBlock.BasicBlock);
        while (workList.Count > 0)
        {
            var current = workList.Pop();
            foreach (var successor in current.Successors)
            {
                if (reachable.Add(successor))
                    workList.Push(successor);
            }
        }

        foreach (BasicBlock block in _cfgBuilder.Blocks)
        {
            if (reachable.Contains(block) || !_unreachableBlocks.Add(block))
                continue;
            foreach (var successor in block.Successors)
                successor.RemovePredecessor(block);
        }
    }

    /// <summary>
    /// Make a true branch.
    /// </summary>
    private void MakeBranchTrue() => MakeIntrinsicBranch(CompareKind.NotEqual);

    /// <summary>
    /// Make a false branch.
    /// </summary>
    private void MakeBranchFalse() => MakeIntrinsicBranch(CompareKind.Equal);

    /// <summary>
    /// Realizes a switch instruction.
    /// </summary>
    /// <param name="branchTargets">All switch branch targets.</param>
    private void MakeSwitch(ILInstructionBranchTargets branchTargets)
    {
        var successors = Block.GetPendingSuccessors(branchTargets.Count);

        var switchValue = Block.PopInt(Location, ConvertFlags.TargetUnsigned);

        // A constant selector (e.g. a folded type test) has a single live target
        if (switchValue is PrimitiveValue constant)
        {
            // IL compares the selector as an unsigned integer
            ulong index = constant.BasicValueType == BasicValueType.Int64
                ? (ulong)constant.Int64Value
                : (uint)constant.Int32Value;
            int liveIndex = index < (ulong)(successors.Length - 1)
                ? (int)index + 1
                : 0;
            var liveTarget = successors[liveIndex];
            var current = Block.BasicBlock;
            if (IsIrreducible)
                goto EmitSwitch;
            Builder.CreateUnconditionalTermination(liveTarget);
            for (int i = 0; i < successors.Length; ++i)
            {
                if (i != liveIndex)
                    successors[i].RemovePredecessor(current);
            }
            PruneUnreachableBlocks();
            return;
        }

    EmitSwitch:
        // Create switch termination with default (first) and cases (rest)
        var switchBuilder = Builder.CreateSwitchTermination(
            switchValue,
            capacity: successors.Length);
        switchBuilder.AddDefault(successors[0]);
        for (int i = 1; i < successors.Length; i++)
            switchBuilder.AddCase(successors[i]);
        switchBuilder.Seal();
    }
}
