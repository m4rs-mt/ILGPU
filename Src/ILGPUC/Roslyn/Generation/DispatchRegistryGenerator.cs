using ILGPUC.Roslyn.Analysis;
using Microsoft.CodeAnalysis.CSharp;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace ILGPUC.Roslyn.Generation;

/// <summary>
/// Generates the code that connects generic kernel launches across assemblies: the
/// summary attribute of a library and the launcher registrations of the assemblies
/// that call it.
/// </summary>
static class DispatchRegistryGenerator
{
    /// <summary>
    /// The file name of the generated summary.
    /// </summary>
    public const string SummaryFileName = "ILGPUKernelDispatchSummary.cs";

    /// <summary>
    /// The file name of the generated registrations.
    /// </summary>
    public const string RegistrationsFileName = "ILGPUKernelDispatchRegistrations.cs";

    /// <summary>
    /// Returns the generated sources for <paramref name="analysis"/>, with file names.
    /// </summary>
    public static IEnumerable<(string FileName, string Source)> Generate(
        AnalysisResult analysis)
    {
        if (analysis.Summaries is { Count: > 0 } summaries)
            yield return (SummaryFileName, GenerateSummary(summaries));
        if (analysis.DispatchRegistrations is { Count: > 0 } registrations)
            yield return (RegistrationsFileName, GenerateRegistrations(registrations));
    }

    /// <summary>
    /// Generates the assembly attribute that describes the kernel launches of the
    /// public generic methods of this assembly.
    /// </summary>
    public static string GenerateSummary(IReadOnlyList<DispatchEntry> summaries)
    {
        var json = KernelDispatchSummary.Serialize(summaries);
        return "// Generated by ILGPU Roslyn Frontend - Kernel Dispatch Summary\n" +
            "[assembly: global::ILGPU.Runtime.KernelDispatchSummary(\n" +
            $"    {SymbolDisplay.FormatLiteral(json, true)})]\n";
    }

    /// <summary>
    /// Generates a module initializer that registers the kernels compiled for the
    /// dispatch code of referenced assemblies.
    /// </summary>
    public static string GenerateRegistrations(
        IReadOnlyList<DispatchRegistration> registrations)
    {
        var sb = new StringBuilder();
        sb.AppendLine(
            "// Generated by ILGPU Roslyn Frontend - Kernel Dispatch Registrations");
        sb.AppendLine("using System;");
        sb.AppendLine("using ILGPU;");
        sb.AppendLine("using ILGPU.Runtime;");
        sb.AppendLine();
        sb.AppendLine("internal static class ILGPUKernelDispatchRegistrations");
        sb.AppendLine("{");
        sb.AppendLine(
            "    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("    internal static void Register()");
        sb.AppendLine("    {");
        foreach (var registration in registrations)
        {
            var kernel = registration.Kernel;
            var types = DispatchStubGenerator.GetLauncherTypeArguments(
                kernel.Variant,
                kernel.Parameters.Select(p =>
                    LauncherStubGenerator.FormatTypeNamePublic(p.Type)));
            if (types.Count > DispatchStubGenerator.MaxLauncherTypeArguments)
                continue;
            sb.AppendLine(
                "        global::ILGPU.Runtime.KernelDispatchRegistry.Register(");
            sb.AppendLine(
                $"            {SymbolDisplay.FormatLiteral(registration.Key, true)},");
            sb.AppendLine(
                $"            (global::System.Action<{string.Join(", ", types)}>)");
            sb.AppendLine($"            {kernel.KernelName}_CompiledKernel.Launch);");
        }
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }
}
