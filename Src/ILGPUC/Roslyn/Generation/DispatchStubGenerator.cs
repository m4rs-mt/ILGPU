using ILGPUC.Roslyn.Analysis;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace ILGPUC.Roslyn.Generation;

/// <summary>
/// Generates a static dispatch class for a kernel launched with open type
/// arguments. The dispatch class has a generic <c>Launch</c> method that matches on
/// <c>typeof()</c> to forward to the compiled kernel class of the matching closed
/// instantiation. The JIT constant-folds the <c>typeof(T) == typeof(int)</c> checks
/// to zero-overhead dispatch. Inline kernels bound to delegate targets dispatch
/// on the keys the targets of the passed delegates are registered under.
/// </summary>
/// <remarks>
/// The <c>Launch</c> method is generic over all type parameters of the kernel
/// definition, including those of its containing types, and takes the kernel's
/// declared parameters. Every launch site of the kernel with open type arguments
/// calls this one method with its own type arguments.
/// </remarks>
static class DispatchStubGenerator
{
    /// <summary>
    /// Generates the C# source of a dispatch stub.
    /// </summary>
    /// <param name="stub">The dispatch stub to generate.</param>
    /// <returns>C# source text for the dispatch stub class.</returns>
    public static string GenerateDispatchStub(DispatchStub stub)
    {
        var definition = stub.KernelDefinition;
        var typeParameters = GenericContext.GetTypeParameters(definition);

        // Type parameters of containing types and of the method may share a name;
        // the stub method needs distinct names.
        var names = new Dictionary<ITypeParameterSymbol, string>(
            SymbolEqualityComparer.Default);
        var usedNames = new HashSet<string>();
        foreach (var typeParameter in typeParameters)
        {
            var name = typeParameter.Name;
            for (int i = 2; !usedNames.Add(name); ++i)
                name = $"{typeParameter.Name}{i}";
            names[typeParameter] = name;
        }

        string? MapName(ITypeParameterSymbol typeParameter) =>
            names.TryGetValue(typeParameter, out var name) ? name : null;
        string Format(ITypeSymbol type) =>
            LauncherStubGenerator.FormatTypeNamePublic(type, MapName);

        var sb = new StringBuilder(4 * 1024);
        sb.AppendLine("// Generated by ILGPU Roslyn Frontend — Dispatch Stub");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using ILGPU;");
        sb.AppendLine("using ILGPU.Runtime;");
        sb.AppendLine();
        sb.AppendLine($"internal static class {stub.Name}_CompiledKernel");
        sb.AppendLine("{");

        var typeParameterList = string.Join(", ", typeParameters.Select(t => names[t]));
        sb.AppendLine($"    internal static void Launch<{typeParameterList}>(");
        sb.AppendLine("        global::ILGPU.Runtime.AcceleratorStream stream,");
        sb.AppendLine("        global::ILGPU.KernelConfig config,");

        int indexDims = GetIndexDimensions(stub.Variant);
        sb.Append("        long userExtent");
        for (int d = 0; d < indexDims && indexDims > 1; d++)
            sb.Append($",\n        int {GetDimensionName(d)}");

        var parameters = stub.LaunchParameters;
        if (parameters.Length == 0)
        {
            sb.AppendLine(")");
        }
        else
        {
            sb.AppendLine(",");
            for (int i = 0; i < parameters.Length; i++)
            {
                var suffix = i < parameters.Length - 1 ? "," : ")";
                sb.AppendLine(
                    $"        {Format(parameters[i].Type)} " +
                    $"{GetParameterName(parameters[i].Name)}{suffix}");
            }
        }

        sb.Append(BuildWhereConstraints(typeParameters, names, Format));
        sb.AppendLine("    {");

        foreach (var specialization in stub.Specializations)
            AppendDispatchCase(sb, stub, specialization, typeParameters, names, Format);

        // Fallback: throw for type arguments without a compiled kernel
        var typeArgNames = string.Join(
            ", ",
            typeParameters.Select(t => $"{{typeof({names[t]})}}"));
        var kernelName = definition is IMethodSymbol
            {
                MethodKind: not MethodKind.AnonymousFunction,
            }
            ? definition.ToDisplayString(
                SymbolDisplayFormat.CSharpShortErrorMessageFormat)
            : stub.KernelName;
        sb.AppendLine("        throw stream.CreateKernelNotSpecializedException(");
        sb.AppendLine($"            $\"{Escape(kernelName)}<{typeArgNames}>\");");

        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// Appends the <c>typeof()</c> test and forwarding call for one closed
    /// instantiation.
    /// </summary>
    private static void AppendDispatchCase(
        StringBuilder sb,
        DispatchStub stub,
        KernelDescriptor specialization,
        IReadOnlyList<ITypeParameterSymbol> typeParameters,
        Dictionary<ITypeParameterSymbol, string> names,
        System.Func<ITypeSymbol, string> format)
    {
        if (specialization.ConcreteTypeArgs is not { } arguments)
            return;

        var conditions = new List<string>();
        for (int i = 0; i < typeParameters.Count && i < arguments.Length; i++)
        {
            var concreteTypeName =
                LauncherStubGenerator.FormatTypeNamePublic(arguments[i]);
            conditions.Add(
                $"typeof({names[typeParameters[i]]}) == typeof({concreteTypeName})");
        }

        sb.AppendLine($"        if ({string.Join("\n            && ", conditions)})");
        sb.AppendLine("        {");
        sb.Append($"            {specialization.KernelName}_CompiledKernel.Launch(");
        sb.AppendLine();
        sb.Append("                stream, config, userExtent");

        int indexDims = GetIndexDimensions(stub.Variant);
        for (int d = 0; d < indexDims && indexDims > 1; d++)
            sb.Append($", {GetDimensionName(d)}");

        // Forward parameters, reinterpreting those whose declared type mentions a
        // type parameter as the closed type of this instantiation
        var parameters = stub.LaunchParameters;
        for (int i = 0; i < parameters.Length; i++)
        {
            var parameter = parameters[i];
            var name = GetParameterName(parameter.Name);
            sb.AppendLine(",");

            if (GenericContext.ContainsTypeParameter(parameter.Type)
                && i < specialization.Parameters.Length)
            {
                var fromType = format(parameter.Type);
                var toType = LauncherStubGenerator.FormatTypeNamePublic(
                    specialization.Parameters[i].Type);
                sb.Append(
                    "                global::System.Runtime.CompilerServices.Unsafe" +
                    $".As<{fromType}, {toType}>(ref {name})");
            }
            else
            {
                sb.Append($"                {name}");
            }
        }

        sb.AppendLine(");");
        sb.AppendLine("            return;");
        sb.AppendLine("        }");
    }

    /// <summary>
    /// Generates a dispatch stub for an inline kernel capturing delegate
    /// parameters, which forwards to the kernel bound to the targets of the
    /// passed delegates:
    /// <code>
    /// if (KernelDelegates.IsRegistered(op, "Program:Host.UnaryOp.op#0"))
    /// {
    ///     InlineKernel_Host_L12_C31_D0_CompiledKernel.Launch(
    ///         stream, config, userExtent, view);
    ///     return;
    /// }
    /// </code>
    /// Delegates that are not registered, such as delegates passed by callers
    /// outside of the compiled project, throw a
    /// <see cref="System.NotSupportedException"/>.
    /// </summary>
    /// <param name="stub">The delegate dispatch stub to generate.</param>
    /// <returns>C# source text for the dispatch stub class.</returns>
    public static string GenerateDelegateDispatchStub(DelegateDispatchStub stub)
    {
        var original = stub.Original;
        var captures = original.DelegateCaptures!.Value;
        var sb = new StringBuilder(4 * 1024);
        sb.AppendLine("// Generated by ILGPU Roslyn Frontend — Dispatch Stub");
        sb.AppendLine("using System;");
        sb.AppendLine("using ILGPU;");
        sb.AppendLine("using ILGPU.Runtime;");
        sb.AppendLine();
        sb.AppendLine($"internal static class {stub.Name}_CompiledKernel");
        sb.AppendLine("{");
        sb.AppendLine("    internal static void Launch(");
        sb.AppendLine("        global::ILGPU.Runtime.AcceleratorStream stream,");
        sb.AppendLine("        global::ILGPU.KernelConfig config,");
        sb.Append("        long userExtent");
        int indexDims = GetIndexDimensions(original.Variant);
        for (int d = 0; d < indexDims && indexDims > 1; d++)
            sb.Append($",\n        int {GetDimensionName(d)}");
        foreach (var param in original.Parameters)
        {
            var type = param.Type.TypeKind == TypeKind.Delegate
                ? param.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                : LauncherStubGenerator.FormatTypeNamePublic(param.Type);
            sb.Append($",\n        {type} @{param.Name}");
        }
        sb.AppendLine(")");
        sb.AppendLine("    {");

        foreach (var binding in stub.Bindings)
        {
            var keys = binding.DelegateKeys!.Value;
            var conditions = captures.Select((capture, i) =>
                $"KernelDelegates.IsRegistered(" +
                $"@{original.Parameters[capture.ParameterIndex].Name}, " +
                $"{SymbolDisplay.FormatLiteral(keys[i], quote: true)})");
            sb.AppendLine(
                $"        if ({string.Join("\n            && ", conditions)})");
            sb.AppendLine("        {");
            sb.Append($"            {binding.KernelName}_CompiledKernel.Launch(");
            sb.AppendLine();
            sb.Append("                stream, config, userExtent");
            for (int d = 0; d < indexDims && indexDims > 1; d++)
                sb.Append($", {GetDimensionName(d)}");
            foreach (var param in binding.Parameters)
                sb.Append($",\n                @{param.Name}");
            sb.AppendLine(");");
            sb.AppendLine("            return;");
            sb.AppendLine("        }");
        }

        // Fallback: throw for delegates whose targets were not compiled
        var method = DelegateTargetDiscoverer.GetDisplayName(
            (IMethodSymbol)captures[0].Parameter.ContainingSymbol);
        var names = string.Join(
            "' or '",
            captures.Select(c => c.Parameter.Name));
        var message =
            $"The delegate passed to '{method}' for '{names}' was not compiled " +
            $"into a kernel. ILGPUC compiles kernels for the lambda expressions " +
            $"and static methods passed to '{method}' in the project launching " +
            $"the kernel. Delegates passed from other assemblies or through " +
            $"reflection, and multicast delegates, are not supported.";
        var literal = SymbolDisplay.FormatLiteral(message, quote: true);
        sb.AppendLine("        throw new NotSupportedException(");
        sb.AppendLine($"            {literal});");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Returns the number of index dimensions passed separately for a variant.
    /// </summary>
    private static int GetIndexDimensions(LaunchVariant variant) =>
        variant switch
        {
            LaunchVariant.Auto2D or LaunchVariant.AutoLong2D
                or LaunchVariant.Auto2DStride
                or LaunchVariant.AutoLong2DStride => 2,
            LaunchVariant.Auto3D or LaunchVariant.AutoLong3D
                or LaunchVariant.Auto3DStride
                or LaunchVariant.AutoLong3DStride => 3,
            _ => 1
        };

    /// <summary>
    /// Returns the name of the parameter carrying the size of a dimension.
    /// </summary>
    private static string GetDimensionName(int dimension) =>
        dimension switch { 0 => "_dimX", 1 => "_dimY", _ => "_dimZ" };

    /// <summary>
    /// Returns the stub's name for a kernel parameter. The prefix keeps it apart
    /// from the stub's own parameters.
    /// </summary>
    private static string GetParameterName(string name) =>
        $"param_{name}";

    /// <summary>
    /// Escapes text for use inside an interpolated string literal.
    /// </summary>
    private static string Escape(string text) =>
        text.Replace("\\", "\\\\", System.StringComparison.Ordinal)
            .Replace("\"", "\\\"", System.StringComparison.Ordinal)
            .Replace("{", "{{", System.StringComparison.Ordinal)
            .Replace("}", "}}", System.StringComparison.Ordinal);

    /// <summary>
    /// Builds <c>where</c> constraint clauses for the given type parameters.
    /// </summary>
    private static string BuildWhereConstraints(
        IReadOnlyList<ITypeParameterSymbol> typeParams,
        Dictionary<ITypeParameterSymbol, string> names,
        System.Func<ITypeSymbol, string> format)
    {
        var constraints = new StringBuilder();
        foreach (var tp in typeParams)
        {
            var parts = new List<string>();
            if (tp.HasUnmanagedTypeConstraint)
                parts.Add("unmanaged");
            else if (tp.HasValueTypeConstraint)
                parts.Add("struct");
            else if (tp.HasReferenceTypeConstraint)
                parts.Add("class");
            foreach (var ct in tp.ConstraintTypes)
                parts.Add(format(ct));
            if (tp.HasConstructorConstraint && !tp.HasValueTypeConstraint)
                parts.Add("new()");
            if (parts.Count > 0)
            {
                constraints.AppendLine(
                    $"        where {names[tp]} : {string.Join(", ", parts)}");
            }
        }
        return constraints.ToString();
    }
}
